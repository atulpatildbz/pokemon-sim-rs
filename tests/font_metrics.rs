//! The game measures text (label widths position the HP gauges), so the advance widths of
//! MS Sans Serif and Arial are compiled in (`src/game/font_metrics.rs`) instead of being read
//! from the OS — they only exist on macOS/Windows. This test regenerates the table
//! (`GEN_FONT_METRICS=1`) or checks it against the system fonts when they are installed.

use std::fmt::Write;

const FONTS: [(&str, &str, &[&str]); 2] = [
    ("MS_SANS_SERIF", "MS Sans Serif", &["/System/Library/Fonts/Supplemental/Microsoft Sans Serif.ttf", "C:\\Windows\\Fonts\\micross.ttf"]),
    ("ARIAL", "Arial", &["/System/Library/Fonts/Supplemental/Arial.ttf", "C:\\Windows\\Fonts\\arial.ttf"]),
];

/// (units per em, advance per Latin-1 code point, -1 = no glyph).
fn table(bytes: &[u8]) -> (u16, Vec<i32>) {
    let face = ttf_parser::Face::parse(bytes, 0).unwrap();
    let adv = (0..256u32)
        .map(|c| {
            let ch = char::from_u32(c).unwrap_or(' ');
            face.glyph_index(ch).map_or(-1, |g| face.glyph_hor_advance(g).unwrap_or(0) as i32)
        })
        .collect();
    (face.units_per_em(), adv)
}

#[test]
fn font_metrics_table() {
    let mut out = String::from("//! Generated by tests/font_metrics.rs (GEN_FONT_METRICS=1) — advance widths in font units.\n\n");
    let mut checked = 0;
    for (konst, family, paths) in FONTS {
        let Some(bytes) = paths.iter().find_map(|p| std::fs::read(p).ok()) else { continue };
        let (upem, adv) = table(&bytes);
        writeln!(out, "/// {family}\npub const {konst}: (u16, [i32; 256]) = ({upem}, {adv:?});\n").unwrap();
        let embedded = match konst {
            "MS_SANS_SERIF" => pokegame::game::font_metrics::MS_SANS_SERIF,
            _ => pokegame::game::font_metrics::ARIAL,
        };
        if std::env::var_os("GEN_FONT_METRICS").is_none() {
            assert_eq!((embedded.0, embedded.1.to_vec()), (upem, adv), "{family} table is stale");
            checked += 1;
        }
    }
    if std::env::var_os("GEN_FONT_METRICS").is_some() {
        std::fs::write(concat!(env!("CARGO_MANIFEST_DIR"), "/src/game/font_metrics.rs"), out).unwrap();
    } else if checked == 0 {
        eprintln!("skipping: system fonts not installed");
    }
}
